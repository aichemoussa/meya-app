"""Builds lib/l10n/translations.dart from the files in this folder.

en.txt holds the English strings, one per line (the keys). Every other
<language>.txt holds the translations on the same lines. A newline inside a
string is written as \\n. Placeholders such as {0} must be kept.

Run from the project folder:  python3 tool/translations/generate.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'lib', 'l10n', 'translations.dart')
LANGS = ['fr', 'ar', 'es', 'de', 'pt_BR', 'pt_PT', 'it', 'zh_Hans', 'ru', 'ja',
         'tr', 'fa', 'hi', 'ur', 'id', 'ko', 'nl', 'bn', 'sw']


def read(name):
    with open(os.path.join(HERE, name + '.txt'), encoding='utf-8') as f:
        lines = f.read().split('\n')
    if lines and lines[-1] == '':
        lines.pop()
    return [line.replace('\\n', '\n') for line in lines]


def quote(text):
    return "'" + (text.replace('\\', '\\\\').replace("'", "\\'")
                  .replace('$', '\\$').replace('\n', '\\n')) + "'"


def main():
    keys = read('en')
    out = ['// Generated by tool/translations/generate.py. Do not edit by hand:',
           '// English text is the key; each map gives the translation.', '',
           'const Map<String, Map<String, String>> meyaTranslations = {']
    ok = True
    for lang in LANGS:
        values = read(lang)
        if len(values) != len(keys):
            print(f'{lang}: {len(values)} lines, expected {len(keys)}')
            ok = False
            continue
        out.append(f"  '{lang}': {{")
        for key, value in zip(keys, values):
            if sorted(re.findall(r'\{\d\}', key)) != sorted(re.findall(r'\{\d\}', value)):
                print(f'{lang}: placeholders differ for {key!r}')
                ok = False
            if key.endswith(' ') and value.rstrip().endswith(':'):
                value = value.rstrip() + ' '
            out.append(f'    {quote(key)}: {quote(value)},')
        out.append('  },')
    out.append('};')
    if not ok:
        sys.exit(1)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('Wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
